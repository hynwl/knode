/**
 * 문장 단위로 자른다 — 튜토리얼 단계 설명을 한 문장씩 줄바꿈해 보여주기 위한 것.
 *
 * 기준은 **문장부호(`.` `?` `!`) 뒤에 공백이 오는 자리**다. 마침표만 보고 자르면
 * `v1.1` · `0.002` · `Ctrl+K.` 같은 것이 함께 잘리는데, 그런 마침표 뒤에는 공백이
 * 없으므로 이 규칙 하나로 걸러진다. 한국어(`…합니다. `)와 영어(`… links. `)가
 * 같은 규칙으로 처리되어 로케일별 분기가 필요 없다.
 */
export function splitSentences(text: string): string[] {
  return text
    .split(/(?<=[.?!])\s+/)
    .map((s) => s.trim())
    .filter(Boolean);
}
